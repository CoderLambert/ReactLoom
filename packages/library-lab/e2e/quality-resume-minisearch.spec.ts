import { expect, test } from '@playwright/test'

test('D20 scoped search and suggestions, fuzzy, rebuild and IME @D20', async ({ page }) => {
  await page.goto('/libraries/minisearch?tab=demo&example=advanced')
  const region = page.getByRole('region', { name: 'MiniSearch 全文倒排索引演示' })
  const input = region.getByRole('textbox', { name: '检索词' })
  const results = region.getByTestId('minisearch-results')
  const submit = region.getByRole('button', { name: '检索', exact: true })
  await input.fill('Nod')
  await submit.click()
  await expect(results).toContainText('开源 Node 工具')
  await expect(region.getByTestId('minisearch-suggestions')).toContainText('node')
  await region.getByRole('combobox', { name: '分类' }).selectOption('技术')
  await expect(results).not.toContainText('Node')
  await expect(region.getByTestId('minisearch-suggestions')).toHaveCount(0)
  await input.fill('Reakt')
  await submit.click()
  await expect(results).toContainText('React')
  await region.getByRole('checkbox', { name: '允许轻微拼写容错' }).uncheck()
  await expect(results.locator('li')).toHaveCount(0)
  await region.getByRole('checkbox', { name: '允许轻微拼写容错' }).check()
  await input.fill('Suspense')
  await submit.click()
  await expect(results).toContainText('React Suspense patterns')
  await region.getByRole('button', { name: '更新 RSS 标题并重建索引' }).click()
  await expect(results.locator('li')).toHaveCount(0)
  await input.fill('Streaming')
  await submit.click()
  await expect(results).toContainText('React Streaming patterns')
  await input.dispatchEvent('compositionstart')
  await input.fill('Node')
  await submit.click()
  await expect(region.getByRole('status')).toContainText('Streaming')
  await input.dispatchEvent('keydown', { key: 'Enter', keyCode: 229, isComposing: true })
  await expect(region.getByRole('status')).toContainText('Streaming')
  await input.dispatchEvent('compositionend')
  await submit.click()
  await expect(region.getByRole('status')).toContainText('Node')
  await expect(results.locator('li')).toHaveCount(0)
  await page.getByRole('button', { name: '停止并卸载', exact: true }).click()
  await expect(region).toHaveCount(0)
  await page.getByRole('button', { name: '运行当前示例', exact: true }).click()
  await expect(
    page
      .getByRole('region', { name: 'MiniSearch 全文倒排索引演示' })
      .getByTestId('minisearch-results'),
  ).toContainText('React Suspense patterns')
})

test('@D20 basic shows real scores and business filters the indexed documents', async ({
  page,
}) => {
  await page.goto('/libraries/minisearch?tab=demo&example=basic')
  const app = page.getByRole('region', { name: 'MiniSearch 全文倒排索引演示', exact: true })
  const results = app.getByTestId('minisearch-results')
  await expect(results).toContainText('React Suspense patterns')
  await expect(results).toContainText('越高越匹配')
  await expect(app.getByRole('combobox', { name: '分类', exact: true })).toHaveCount(0)
  await page.goto('/libraries/minisearch?tab=demo&example=business')
  await app.getByRole('textbox', { name: '检索词', exact: true }).fill('')
  await app.getByRole('button', { name: '检索', exact: true }).click()
  await app.getByRole('combobox', { name: '分类', exact: true }).selectOption('产品')
  await expect(results.locator('li')).toHaveCount(1)
  await expect(results).toContainText('创业产品增长')
  await expect(results).not.toContainText('React')
})
