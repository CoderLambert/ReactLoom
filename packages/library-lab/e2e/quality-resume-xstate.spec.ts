import { expect, test } from '@playwright/test'

test('@D14 explicit review transitions and Unicode reason policy', async ({ page }) => {
  await page.goto('/libraries/xstate?tab=demo&example=business')
  const app = page.getByRole('region', { name: 'XState真实状态机演示', exact: true })
  const state = app.getByTestId('xstate-state')
  await expect(app.getByRole('button', { name: '批准发布', exact: true })).toBeDisabled()
  await app.getByRole('button', { name: '提交审核', exact: true }).click()
  const input = app.getByRole('textbox', { name: '拒绝原因（最多200个码点）', exact: true })
  const reject = app.getByRole('button', { name: '驳回', exact: true })
  await input.fill('   ')
  await expect(reject).toBeDisabled()
  await input.fill('😀'.repeat(201))
  await expect(reject).toBeDisabled()
  await expect(state).toContainText('状态：reviewing')
  await input.fill(`  ${'😀'.repeat(200)}  `)
  await expect(reject).toBeEnabled()
  await reject.click()
  await expect(state).toContainText('状态：rejected')
  await expect(state).toContainText(`最后拒绝原因：${'😀'.repeat(200)}`)
  await app.getByRole('button', { name: '重新开始', exact: true }).click()
  await app.getByRole('button', { name: '提交审核', exact: true }).click()
  await app.getByRole('button', { name: '批准发布', exact: true }).click()
  await expect(state).toContainText('状态：published')
})

test('@D14 retry budget is visible and actor is fresh after unmount', async ({ page }) => {
  await page.goto('/libraries/xstate?tab=demo&example=advanced')
  const app = page.getByRole('region', { name: 'XState真实状态机演示', exact: true })
  const state = app.getByTestId('xstate-state')
  await app.getByRole('button', { name: '提交审核', exact: true }).click()
  for (let retry = 1; retry <= 2; retry++) {
    await app.getByRole('button', { name: '驳回', exact: true }).click()
    await app.getByRole('button', { name: '重试审核', exact: true }).click()
    await expect(state).toContainText(`已重试 ${retry}/2`)
    await expect(state).toContainText('状态：reviewing')
  }
  await app.getByRole('button', { name: '驳回', exact: true }).click()
  await expect(app.getByRole('button', { name: '重试审核', exact: true })).toBeDisabled()
  await expect(state).toContainText('状态：rejected')
  await page.getByRole('button', { name: '停止并卸载', exact: true }).click()
  await expect(app).toHaveCount(0)
  await page.getByRole('button', { name: '运行当前示例', exact: true }).click()
  await expect(state).toContainText('状态：draft')
  await expect(state).toContainText('已重试 0/2')
  await expect(app.getByRole('button', { name: '批准发布', exact: true })).toBeDisabled()
})

