import { expect, test } from '@playwright/test'

test('D06 observes sharing, ID edits, batch no-op and isolated inverse rollback @D06', async ({
  page,
}) => {
  await page.goto('/libraries/immer?tab=demo&example=basic')
  const input = page.getByRole('textbox', { name: '分组名' })
  await input.fill('开源')
  await page.getByRole('button', { name: '更新分组', exact: true }).click()
  await expect(page.getByTestId('immer-state')).toContainText('开源')
  await expect(page.getByTestId('immer-previous')).toContainText('前端工程')
  await expect(page.getByTestId('immer-references')).toContainText('"storiesArrayShared": true')
  await page.getByRole('button', { name: '更新分组', exact: true }).click()
  await expect(page.getByTestId('immer-references')).toContainText('"rootShared": true')
  await page.goto('/libraries/immer?tab=demo&example=business')
  await page.getByRole('checkbox', { name: 'React 19 生命周期' }).check()
  await expect(page.getByTestId('immer-references')).toContainText('"shared": false')
  await expect(page.getByTestId('immer-references')).toContainText('"shared": true')
  await page.getByRole('button', { name: '全部标记已读' }).click()
  await page.getByRole('button', { name: '全部标记已读' }).click()
  await expect(page.getByTestId('immer-references')).toContainText('"rootShared": true')
  await page.goto('/libraries/immer?tab=demo&example=advanced')
  const baseline = await page.getByTestId('immer-state').textContent()
  await page.getByRole('button', { name: '生成乐观更新' }).click()
  await expect(input).toBeDisabled()
  await expect(page.getByTestId('immer-state')).toContainText('optimistic-')
  await page.getByRole('button', { name: '模拟失败并撤销' }).click()
  await expect(page.getByTestId('immer-state')).toHaveText(baseline ?? '')
  await page.getByRole('button', { name: '生成乐观更新' }).click()
  await page.getByRole('button', { name: '确认本地变更' }).click()
  await expect(page.getByRole('button', { name: '模拟失败并撤销' })).toBeDisabled()
  await expect(input).toBeEnabled()
  await page.getByRole('button', { name: '停止并卸载', exact: true }).click()
  await expect(page.getByTestId('immer-state')).toHaveCount(0)
  await page.getByRole('button', { name: '运行当前示例', exact: true }).click()
  await expect(page.getByTestId('immer-state')).not.toContainText('optimistic-')
})
