import test from 'node:test';
import assert from 'node:assert/strict';
import {validatePdfLayout,validateOutputPdf,PDF_LIMITS} from './document-policy.mjs';
function fakePdf(dimensions) {
  return {getPageCount:()=>dimensions.length,getPages:()=>dimensions.map(([width,height])=>({getSize:()=>({width,height})}))};
}
test('accepts normal A4 documents and output byte arrays', () => {
  assert.equal(validatePdfLayout(fakePdf([[595,842],[595,842]])),2);
  assert.equal(validateOutputPdf(new Uint8Array(1024)).byteLength,1024);
});
test('rejects zero, huge and mismatched page inventories', () => {
  assert.throws(()=>validatePdfLayout(fakePdf([])),/page count/);
  assert.throws(()=>validatePdfLayout(fakePdf(Array(21).fill([595,842]))),/page count/);
  assert.throws(()=>validatePdfLayout({getPageCount:()=>1,getPages:()=>[]}),/inventory/);
});
test('rejects giant, degenerate and nonfinite MediaBox dimensions', () => {
  for(const width of [0,35,2001,Number.NaN,Number.POSITIVE_INFINITY]) {
    assert.throws(()=>validatePdfLayout(fakePdf([[width,842]])),/dimensions/);
  }
});
test('caps generated bytes before Blob URL allocation', () => {
  for(const invalid of [new Uint8Array(9),new Uint8Array(PDF_LIMITS.maxOutputBytes+1),new ArrayBuffer(100)]) {
    assert.throws(()=>validateOutputPdf(invalid),/size/);
  }
});
