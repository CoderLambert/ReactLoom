import { expect, test } from '@playwright/test'

test('@D02 collection order changes retained duplicate', async ({ page }) => {
  await page.goto('/libraries/lodash?tab=demo&example=basic')
  const output = page.getByTestId('d02-collection')
  await expect(output).toContainText('模型推理实践')
  await expect(output).not.toContainText('重复但高分')
  await page.getByLabel('先按分数排序再去重').check()
  await expect(output).toContainText('重复但高分')
  await expect(output).not.toContainText('模型推理实践')
})

test('@D02 flush cancel composition and persistent unmount observer', async ({ page }) => {
  await page.goto('/libraries/lodash?tab=demo&example=advanced')
  const input = page.getByLabel('待提交查询')
  const events = page.getByTestId('d02-events')
  await input.fill('first')
  await page.getByRole('button', { name: 'flush 立即提交' }).click()
  await expect(events).toHaveText('["first"]')
  await page.waitForTimeout(500)
  await expect(events).toHaveText('["first"]')
  await input.fill('cancelled')
  await page.getByRole('button', { name: 'cancel 待执行调用' }).click()
  await page.waitForTimeout(500)
  await expect(events).toHaveText('["first"]')
  await input.dispatchEvent('compositionstart')
  await input.fill('zhong')
  await page.waitForTimeout(500)
  await expect(events).toHaveText('["first"]')
  await input.fill('中文')
  await input.dispatchEvent('compositionend', { data: '中文' })
  await expect(events).toHaveText('["first","中文"]')
  await input.fill('must-not-submit')
  await page.getByRole('button', { name: '卸载输入并观察' }).click()
  await expect(page.getByTestId('d02-observation')).toHaveText('观察完成：卸载后新增 0 次')
  await expect(events).toHaveText('["first","中文"]')
  await page.getByRole('button', { name: '重新挂载输入' }).click()
  await input.fill('recovered')
  await expect(events).toHaveText('["first","中文","recovered"]')
})
